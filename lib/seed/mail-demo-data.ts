export function demoMailToMailItem(
  row: DemoMailSeed,
  daysFromNow: (n: number) => Date,
  iso: (d: Date) => string
): MailItem {
  const mailDate = daysFromNow(row.mailDateOffset);
  const updatedAt = daysFromNow(row.updatedAtOffset ?? row.mailDateOffset);
  const attachments: DgMailAttachment[] = (row.attachments ?? []).map((a) => ({
    ...a,
    mailId: row.id,
    uploadedAt: iso(mailDate),
  }));

  return {
    id: row.id,
    direction: row.direction,
    mailKind: row.mailKind ?? 'DEPARTURE',
    registrationNumber: row.registrationNumber,
    reference: row.reference,
    counterpart: row.counterpart,
    subject: row.subject,
    mailDate: iso(mailDate),
    priority: row.priority,
    workflowStatus: row.workflowStatus,
    origin: row.origin,
    dgaInstruction: row.dgaInstruction,
    executor: row.executor,
    action: row.action,
    scSentAt: row.scSentAtOffset !== null ? iso(daysFromNow(row.scSentAtOffset)) : null,
    executionDeadline:
      row.executionDeadlineOffset !== null ? iso(daysFromNow(row.executionDeadlineOffset)) : null,
    followUp: row.followUp,
    courierName: row.courierName,
    assignedService: row.assignedService,
    assignedAt:
      row.assignedAtOffset != null
        ? iso(daysFromNow(row.assignedAtOffset))
        : row.workflowStatus === 'ASSIGNED'
          ? iso(updatedAt)
          : null,
    attachmentCount: row.attachmentCount,
    attachments,
    notes: row.notes,
    archived: false,
    archivedAt: null,
    createdAt: iso(mailDate),
    updatedAt: iso(updatedAt),
  };
}

export function demoMailToPrismaCreate(
  row: DemoMailSeed,
  daysFromNow: (n: number) => Date
) {
  const updatedAt = daysFromNow(row.updatedAtOffset ?? row.mailDateOffset);
  return {
    id: row.id,
    direction: row.direction,
    mailKind: row.mailKind ?? 'DEPARTURE',
    registrationNumber: row.registrationNumber,
    reference: row.reference,
    counterpart: row.counterpart,
    subject: row.subject,
    mailDate: daysFromNow(row.mailDateOffset),
    priority: row.priority,
    workflowStatus: row.workflowStatus,
    origin: row.origin,
    dgaInstruction: row.dgaInstruction,
    executor: row.executor,
    action: row.action,
    scSentAt: row.scSentAtOffset !== null ? daysFromNow(row.scSentAtOffset) : null,
    executionDeadline:
      row.executionDeadlineOffset !== null ? daysFromNow(row.executionDeadlineOffset) : null,
    followUp: row.followUp,
    courierName: row.courierName,
    assignedService: row.assignedService,
    assignedAt:
      row.assignedAtOffset != null
        ? daysFromNow(row.assignedAtOffset)
        : row.workflowStatus === 'ASSIGNED'
          ? updatedAt
          : null,
    attachmentCount: row.attachmentCount,
    notes: row.notes,
    archived: false,
    createdAt: daysFromNow(row.mailDateOffset),
    updatedAt,
    attachments: row.attachments?.length
      ? {
          create: row.attachments.map((a) => ({
            id: a.id,
            fileName: a.fileName,
            fileSize: a.fileSize,
            mimeType: a.mimeType,
            storageKey: a.storageKey,
          })),
        }
      : undefined,
  };
}
